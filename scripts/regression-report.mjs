/**
 * scripts/regression-report.mjs
 * WP-0.0: Generates tests/reports/regression.html and regression.md
 * Shows all 87 bug IDs → PASS/FAIL/NO-TEST status and QA score.
 *
 * Usage: node scripts/regression-report.mjs [path/to/vitest-report.json]
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// ─── Load bug registry ────────────────────────────────────────────────────────
const registry = JSON.parse(readFileSync(join(root, 'tests/regression/bug-registry.json'), 'utf-8'));

// ─── Load Vitest JSON report (if exists) ─────────────────────────────────────
const reportPath = process.argv[2] || join(root, 'tests/reports/vitest-results.json');
let vitestResults = null;
if (existsSync(reportPath)) {
  try {
    vitestResults = JSON.parse(readFileSync(reportPath, 'utf-8'));
  } catch {}
}

// ─── Determine status per bug ─────────────────────────────────────────────────
const WEIGHT = { Critical: 5, High: 3, Medium: 1, Low: 0.5 };
const MAX_SCORE = registry.reduce((s, b) => s + (WEIGHT[b.severity] || 1), 0);

function getBugStatus(bug) {
  if (!bug.tests || bug.tests.length === 0) return 'NO-TEST';
  
  if (!vitestResults) return 'PENDING'; // No test run results yet
  
  // Look for test results matching this bug's ID
  const bugPattern = `[${bug.id}]`;
  let passed = 0, failed = 0, total = 0;
  
  // Parse vitest JSON results structure
  const allTests = vitestResults?.testResults || vitestResults?.results || [];
  for (const suite of allTests) {
    const assertionResults = suite.assertionResults || suite.tests || [];
    for (const test of assertionResults) {
      if (test.fullName?.includes(bugPattern) || test.name?.includes(bugPattern)) {
        total++;
        if (test.status === 'passed') passed++;
        else failed++;
      }
    }
  }
  
  if (total === 0) return 'NO-TEST';
  if (failed > 0) return 'FAIL';
  return 'PASS';
}

const results = registry.map(bug => ({
  ...bug,
  status: getBugStatus(bug),
}));

const passCount = results.filter(r => r.status === 'PASS').length;
const failCount = results.filter(r => r.status === 'FAIL').length;
const noTestCount = results.filter(r => r.status === 'NO-TEST').length;
const pendingCount = results.filter(r => r.status === 'PENDING').length;

// QA Score: earned points from PASS bugs / max possible
const earnedPoints = results
  .filter(r => r.status === 'PASS')
  .reduce((s, b) => s + (WEIGHT[b.severity] || 1), 0);
const qaScore = Math.round((earnedPoints / MAX_SCORE) * 100);

const runTime = new Date().toISOString();

// ─── Generate Markdown report ─────────────────────────────────────────────────
const severityEmoji = { Critical: '🔴', High: '🟠', Medium: '🟡', Low: '⚪' };
const statusEmoji = { PASS: '✅', FAIL: '❌', 'NO-TEST': '⬜', PENDING: '⏳' };

let md = `# GuestFlow PMS Regression Report
> Generated: ${runTime}  
> QA Score: **${qaScore}/100** (target ≥70 after Phase 0)

## Summary

| Status | Count |
|--------|-------|
| ✅ PASS | ${passCount} |
| ❌ FAIL | ${failCount} |
| ⬜ NO-TEST | ${noTestCount} |
| ⏳ PENDING | ${pendingCount} |
| **Total** | **${registry.length}** |

---

## Bug Status by Severity

`;

for (const severity of ['Critical', 'High', 'Medium', 'Low']) {
  const bugs = results.filter(r => r.severity === severity);
  md += `### ${severityEmoji[severity]} ${severity} (${bugs.length} bugs)\n\n`;
  md += `| Bug ID | Status | Module | Title | WP |\n`;
  md += `|--------|--------|--------|-------|----|\n`;
  for (const bug of bugs) {
    const title = bug.title.length > 60 ? bug.title.substring(0, 57) + '...' : bug.title;
    md += `| \`${bug.id}\` | ${statusEmoji[bug.status]} ${bug.status} | ${bug.module} | ${title} | ${bug.wp} |\n`;
  }
  md += '\n';
}

md += `\n---\n*Report generated by scripts/regression-report.mjs*\n`;

// ─── Generate HTML report ─────────────────────────────────────────────────────
const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>GuestFlow Regression Report</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 1200px; margin: 0 auto; padding: 20px; background: #0f172a; color: #e2e8f0; }
  h1, h2, h3 { color: #f1f5f9; }
  .score { font-size: 3rem; font-weight: bold; color: ${qaScore >= 70 ? '#22c55e' : qaScore >= 50 ? '#f59e0b' : '#ef4444'}; }
  .summary { display: flex; gap: 20px; margin: 20px 0; }
  .stat { background: #1e293b; padding: 16px 24px; border-radius: 8px; text-align: center; }
  .stat .n { font-size: 2rem; font-weight: bold; }
  .stat .l { font-size: 0.8rem; color: #94a3b8; }
  table { width: 100%; border-collapse: collapse; margin: 10px 0 30px 0; }
  th { background: #1e293b; padding: 8px 12px; text-align: left; color: #94a3b8; font-size: 0.8rem; }
  td { padding: 6px 12px; border-bottom: 1px solid #1e293b; font-size: 0.85rem; }
  tr:hover td { background: #1e293b44; }
  .PASS { color: #22c55e; }
  .FAIL { color: #ef4444; }
  .NO-TEST { color: #64748b; }
  .PENDING { color: #f59e0b; }
  .Critical td:first-child { border-left: 3px solid #ef4444; }
  .High td:first-child { border-left: 3px solid #f97316; }
  .Medium td:first-child { border-left: 3px solid #eab308; }
  .Low td:first-child { border-left: 3px solid #94a3b8; }
  .badge { display: inline-block; padding: 2px 8px; border-radius: 4px; font-size: 0.75rem; background: #1e293b; }
</style>
</head>
<body>
<h1>🏨 GuestFlow PMS Regression Report</h1>
<p style="color:#94a3b8">Generated: ${runTime}</p>

<div class="score">${qaScore}<span style="font-size:1.5rem">/100</span></div>
<p style="color:#94a3b8">Target: 70+ after Phase 0 | Baseline: 22/100 (21 Nov 2026 audit)</p>

<div class="summary">
  <div class="stat"><div class="n" style="color:#22c55e">${passCount}</div><div class="l">PASS</div></div>
  <div class="stat"><div class="n" style="color:#ef4444">${failCount}</div><div class="l">FAIL</div></div>
  <div class="stat"><div class="n" style="color:#64748b">${noTestCount}</div><div class="l">NO TEST</div></div>
  <div class="stat"><div class="n" style="color:#f59e0b">${pendingCount}</div><div class="l">PENDING</div></div>
  <div class="stat"><div class="n">${registry.length}</div><div class="l">TOTAL BUGS</div></div>
</div>

<h2>Bug Status</h2>
<table>
<thead><tr><th>Bug ID</th><th>Severity</th><th>Status</th><th>Module</th><th>Title</th><th>WP</th></tr></thead>
<tbody>
${results.map(b => `
<tr class="${b.severity}">
  <td><code>${b.id}</code></td>
  <td><span class="badge">${severityEmoji[b.severity]} ${b.severity}</span></td>
  <td class="${b.status}">${statusEmoji[b.status]} ${b.status}</td>
  <td>${b.module}</td>
  <td style="max-width:400px">${b.title}</td>
  <td><span class="badge">${b.wp}</span></td>
</tr>`).join('')}
</tbody>
</table>

<footer style="color:#475569;font-size:0.75rem;margin-top:40px">
Generated by scripts/regression-report.mjs | OrderMint PMS / GuestFlow
</footer>
</body>
</html>`;

// ─── Write outputs ────────────────────────────────────────────────────────────
const reportsDir = join(root, 'tests/reports');
mkdirSync(reportsDir, { recursive: true });

writeFileSync(join(reportsDir, 'regression.md'), md);
writeFileSync(join(reportsDir, 'regression.html'), html);

console.log(`\n✅ Regression report generated`);
console.log(`   Score: ${qaScore}/100`);
console.log(`   PASS: ${passCount} | FAIL: ${failCount} | NO-TEST: ${noTestCount}`);
console.log(`   HTML: tests/reports/regression.html`);
console.log(`   MD:   tests/reports/regression.md\n`);
